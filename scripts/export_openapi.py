#!/usr/bin/env python3
"""Export the relay's OpenAPI schema to ``docs/api/openapi.yaml``.

Boots ``create_app()`` with a throwaway config generated into a temp
directory (ephemeral P-256 + Ed25519 keys — never real ones), so the
exported schema always matches the code. Run from the repo root:

    uv run python scripts/export_openapi.py
"""

from __future__ import annotations

import sys
import tempfile
from pathlib import Path

import yaml
from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import ec

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT / "src"))

from apns_relay.app import create_app
from apns_relay.config import load_config

CONFIG_YAML = """\
server:
  api_domain: api.example.org
  docs_domain: docs.example.org
enrollment:
  grant_issuer_key: keys/issuer.pem
storage:
  database: relay.db
apps:
  - id: example-app
    display_name: Example App
    bundle_id: com.example.app
    team_id: ABCDEFGHIJ
    key_file: keys/AuthKey_ABCDEFGHIJ.p8
    environments: [sandbox, production]
    kinds: [alert, background, liveActivity]
    live_activity: true
    attest_environment: production
    registration: { callback_required: false }
    caps: { title: 64, subtitle: 64, body: 200, sealed: 1024, category: 32, background: 512 }
    quota: { burst_per_min: 60, daily: 10000, token_burst_per_min: 30 }
    grant_ttl: { min: 900, max: 86400, default: 21600 }
"""


def build_schema() -> dict:
    with tempfile.TemporaryDirectory(prefix="relay-openapi-") as tmp:
        base = Path(tmp)
        (base / "keys").mkdir()
        (base / "config.yaml").write_text(CONFIG_YAML)

        # Ephemeral P-256 provider key with an AuthKey_ filename.
        provider = ec.generate_private_key(ec.SECP256R1())
        (base / "keys" / "AuthKey_ABCDEFGHIJ.p8").write_bytes(
            provider.private_bytes(
                serialization.Encoding.PEM,
                serialization.PrivateFormat.PKCS8,
                serialization.NoEncryption(),
            )
        )
        # Ephemeral Ed25519 issuer key.
        from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey

        issuer = Ed25519PrivateKey.generate()
        (base / "keys" / "issuer.pem").write_bytes(
            issuer.private_bytes(
                serialization.Encoding.PEM,
                serialization.PrivateFormat.PKCS8,
                serialization.NoEncryption(),
            )
        )

        config = load_config(base / "config.yaml", admin_token="x" * 32)
        app = create_app(config, master_secret=b"m" * 32)
        return app.openapi()


def main(argv: list[str]) -> int:
    out = Path(argv[1]) if len(argv) > 1 else REPO_ROOT / "docs" / "api" / "openapi.yaml"
    schema = build_schema()
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(
        "# Generated by scripts/export_openapi.py — do not edit by hand.\n"
        + yaml.safe_dump(schema, sort_keys=False, width=100)
    )
    print(f"wrote {out} ({out.stat().st_size} bytes, {len(schema.get('paths', {}))} paths)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
